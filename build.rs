//! Embed the viewer's `trunk` output into the bridge binary.
//!
//! The deployable artifact is **one file** (board-b0o): a browser fetches the wasm from the same
//! origin that serves the websocket, and it comes out of the binary's own memory. A sidecar
//! `dist/` next to the executable would leave the bridge and the UI able to drift — deploy a new
//! binary and forget to copy the files, and the viewer parses a payload it was not built for.
//!
//! `viewer/dist` is gitignored, so a plain `cargo build` on a fresh checkout embeds a placeholder
//! page instead of failing. A Nix build stages the real `dist` (from `packages.wasm`) into place
//! before cargo runs; `just web` does the same for a local build.

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets this"));
    let dist = env::var_os("SOLAR_VIEWER_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("viewer").join("dist"));

    println!("cargo:rerun-if-changed=viewer/dist");
    println!("cargo:rerun-if-env-changed=SOLAR_VIEWER_DIST");

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
    }
    files.sort();

    let mut code = String::from("// @generated by build.rs — do not edit.\n");
    if files.is_empty() {
        println!(
            "cargo:warning=viewer/dist is missing; the bridge will serve a placeholder page. Run `just web` before building."
        );
        code.push_str(&format!(
            "pub const EMBEDDED: bool = false;\npub static ASSETS: &[(&str, &[u8])] = &[(\"index.html\", {PLACEHOLDER})];\n"
        ));
    } else {
        code.push_str("pub const EMBEDDED: bool = true;\n");
        code.push_str("pub static ASSETS: &[(&str, &[u8])] = &[\n");
        for (relative, absolute) in &files {
            code.push_str(&format!(
                "    ({relative:?}, include_bytes!({:?})),\n",
                absolute.to_str().expect("utf-8 paths")
            ));
        }
        code.push_str("];\n");
        println!(
            "cargo:warning=embedded the viewer: {} files from {}",
            files.len(),
            dist.display()
        );
    }

    fs::write(
        PathBuf::from(env::var("OUT_DIR").expect("cargo sets this")).join("assets.rs"),
        code,
    )
    .expect("writing the generated asset table");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(relative) = path.strip_prefix(root) {
            out.push((relative.to_string_lossy().replace('\\', "/"), path));
        }
    }
}

